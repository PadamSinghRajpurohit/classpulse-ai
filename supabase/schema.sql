-- ClassPulse remote storage schema. Tables are project-prefixed and protected by
-- Row Level Security. Raw camera/audio media and face biometrics are never stored.

create table if not exists public.classpulse_session_summaries (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null references auth.users (id) on delete cascade,
    class_name text not null check (char_length(class_name) between 1 and 120),
    started_at timestamptz not null default now(),
    ended_at timestamptz,
    enrollment_count integer not null default 0 check (enrollment_count >= 0),
    attendance_count integer not null default 0 check (attendance_count >= 0),
    engagement_score real check (engagement_score between 0 and 100),
    participation_count integer not null default 0 check (participation_count >= 0),
    summary jsonb not null default '{}'::jsonb,
    constraint classpulse_attendance_within_enrollment
        check (attendance_count <= enrollment_count),
    constraint classpulse_summary_aggregate_keys_only
        check (summary - 'trend_points' - 'video_quality' - 'audio_quality' - 'recommendation_codes' = '{}'::jsonb)
);

create index if not exists classpulse_owner_started_idx
    on public.classpulse_session_summaries (owner_id, started_at desc);

alter table public.classpulse_session_summaries enable row level security;
alter table public.classpulse_session_summaries force row level security;
revoke all on table public.classpulse_session_summaries from anon;
grant select, insert, update, delete on public.classpulse_session_summaries to authenticated;

-- Idempotent and non-destructive policy creation.
do $$
begin
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'classpulse_session_summaries' and policyname = 'classpulse_read_own') then
        create policy classpulse_read_own on public.classpulse_session_summaries for select to authenticated using (owner_id = (select auth.uid()));
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'classpulse_session_summaries' and policyname = 'classpulse_insert_own') then
        create policy classpulse_insert_own on public.classpulse_session_summaries for insert to authenticated with check (owner_id = (select auth.uid()));
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'classpulse_session_summaries' and policyname = 'classpulse_update_own') then
        create policy classpulse_update_own on public.classpulse_session_summaries for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'classpulse_session_summaries' and policyname = 'classpulse_delete_own') then
        create policy classpulse_delete_own on public.classpulse_session_summaries for delete to authenticated using (owner_id = (select auth.uid()));
    end if;
end $$;

-- Durable, owner-scoped classroom data for Supabase-authenticated users.
-- Local-only installs continue to use SQLite. Raw camera/audio media is never stored.

create table if not exists public.classpulse_classes (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    name text not null check (char_length(name) between 1 and 100),
    created_at timestamptz not null default now(),
    unique(owner_id, name),
    unique(owner_id, id)
);

create table if not exists public.classpulse_students (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    student_code text not null check (char_length(student_code) between 1 and 64),
    name text not null check (char_length(name) between 1 and 100),
    created_at timestamptz not null default now(),
    unique(owner_id, student_code),
    unique(owner_id, id)
);

create table if not exists public.classpulse_class_students (
    owner_id uuid not null references auth.users(id) on delete cascade,
    class_id bigint not null,
    student_id bigint not null,
    created_at timestamptz not null default now(),
    primary key(class_id, student_id),
    foreign key(owner_id, class_id) references public.classpulse_classes(owner_id, id) on delete cascade,
    foreign key(owner_id, student_id) references public.classpulse_students(owner_id, id) on delete cascade
);

create table if not exists public.classpulse_attendance_records (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    student_pk bigint not null,
    session_date date not null,
    class_name text not null check (char_length(class_name) between 1 and 120),
    status text not null check (status in ('present', 'absent', 'late', 'excused')),
    marked_at timestamptz not null default now(),
    unique(owner_id, student_pk, session_date, class_name),
    foreign key(owner_id, student_pk) references public.classpulse_students(owner_id, id) on delete cascade
);

create table if not exists public.classpulse_data_migrations (
    owner_id uuid not null references auth.users(id) on delete cascade,
    migration_key text not null,
    applied_at timestamptz not null default now(),
    primary key(owner_id, migration_key)
);

create index if not exists classpulse_classes_owner_idx
    on public.classpulse_classes(owner_id, name);
create index if not exists classpulse_class_students_owner_idx
    on public.classpulse_class_students(owner_id, class_id);
create index if not exists classpulse_attendance_owner_date_idx
    on public.classpulse_attendance_records(owner_id, session_date desc);

alter table public.classpulse_classes enable row level security;
alter table public.classpulse_classes force row level security;
alter table public.classpulse_students enable row level security;
alter table public.classpulse_students force row level security;
alter table public.classpulse_class_students enable row level security;
alter table public.classpulse_class_students force row level security;
alter table public.classpulse_attendance_records enable row level security;
alter table public.classpulse_attendance_records force row level security;
alter table public.classpulse_data_migrations enable row level security;
alter table public.classpulse_data_migrations force row level security;

revoke all on public.classpulse_classes, public.classpulse_students,
    public.classpulse_class_students, public.classpulse_attendance_records,
    public.classpulse_data_migrations from anon;
grant select, insert, update, delete on public.classpulse_classes,
    public.classpulse_students, public.classpulse_class_students,
    public.classpulse_attendance_records, public.classpulse_data_migrations to authenticated;
grant usage, select on sequence public.classpulse_classes_id_seq,
    public.classpulse_students_id_seq,
    public.classpulse_attendance_records_id_seq to authenticated;

do $$
declare tbl text;
begin
    foreach tbl in array array[
        'classpulse_classes', 'classpulse_students',
        'classpulse_class_students', 'classpulse_attendance_records',
        'classpulse_data_migrations'
    ] loop
        execute format('drop policy if exists %I on public.%I', tbl || '_read_own', tbl);
        execute format('create policy %I on public.%I for select to authenticated using (owner_id = (select auth.uid()))', tbl || '_read_own', tbl);
        execute format('drop policy if exists %I on public.%I', tbl || '_insert_own', tbl);
        execute format('create policy %I on public.%I for insert to authenticated with check (owner_id = (select auth.uid()))', tbl || '_insert_own', tbl);
        execute format('drop policy if exists %I on public.%I', tbl || '_update_own', tbl);
        execute format('create policy %I on public.%I for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()))', tbl || '_update_own', tbl);
        execute format('drop policy if exists %I on public.%I', tbl || '_delete_own', tbl);
        execute format('create policy %I on public.%I for delete to authenticated using (owner_id = (select auth.uid()))', tbl || '_delete_own', tbl);
    end loop;
end $$;

